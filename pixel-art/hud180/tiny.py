def text(c, s, x, y, colour):
    """Draw s on a Px canvas; returns the width."""
    x0 = x
    for ch in s.upper() if s.upper() in s.upper() else s:
        g = G.get(ch, G.get(ch.upper(), G[" "]))
        for yy, row in enumerate(g):
            for xx, v in enumerate(row):
                if v == "1":
                    c.p(x + xx, y + yy, colour)
        x += len(g[0]) + 1
    return x - x0 - 1


def width(s):
    return sum(len(G.get(ch.upper(), G[" "])[0]) + 1 for ch in s) - 1
