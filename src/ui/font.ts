// Foldworks' three bitmap faces (the 180, docs/hud-180.md "Typography"), drawn for this game and
// sharing no glyph with the Sprocket & Sprout font the engine layer came with:
//
//   Reed      the body face: cap 7, x-height 5, descenders 2. 2 px verticals, 1 px horizontals,
//             rounded bowls, open apertures, single-storey a and g, a hooked t. Figures 5 wide.
//   Bullfrog  the display face: cap 9, x-height 7, descenders 2. 2 px strokes, soft corners, a few
//             round letters sit 1 px low (the bounce). Figures 7 wide.
//   Pip       the small face: cap 5, capitals only (lowercase draws as capitals). Figures 4 wide.
//
// A glyph is its rows top to bottom, '#' ink and '.' paper, every row the same width. Row 0 is
// the cap line; the baseline is the last cap row (6 in Reed, 8 in Bullfrog, 4 in Pip) and
// descenders hang below it. A glyph may be shorter than its face (the rest is blank) and a
// bouncing Bullfrog letter simply starts with a blank row. Each face is pre-rendered into a white
// atlas once, and once more per colour it is drawn in (`source-in` tint), so a string costs one
// drawImage per glyph.
//
// Pixel art: pixel-art/fonts/sheet.py renders the contact sheet (pixel-art/fonts/out/fonts.png)
// straight from these tables, beside the old S&S face and Last Watt's HUD.

