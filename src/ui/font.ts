// ------------------------------------------------------------------------------- the faces

interface Glyph { w: number; rows: string[]; ax: number; ay: number }

/** One face: its glyphs, its white atlas and one tinted copy per colour drawn. */
class Face {
  readonly glyphs = new Map<string, Glyph>();
  private white: HTMLCanvasElement | null = null;
  private readonly tinted = new Map<string, HTMLCanvasElement>();
  private readonly cellW: number;
  private readonly cellH: number; // the face's height, or more where a glyph hangs below it (Pip's comma)

  constructor(table: Record<string, string>, readonly h: number, private readonly caps: boolean) {
    let maxW = 1;
    let maxH = h;
    for (const [ch, def] of Object.entries(table)) {
      const rows = def.split('|');
      this.glyphs.set(ch, { w: rows[0].length, rows, ax: 0, ay: 0 });
      maxW = Math.max(maxW, rows[0].length);
      maxH = Math.max(maxH, rows.length);
    }
    this.cellW = maxW + 1;
    this.cellH = maxH;
  }

  has(ch: string): boolean {
    return this.glyphs.has(ch) || (this.caps && this.glyphs.has(ch.toUpperCase()));
  }

  get(ch: string): Glyph {
    return this.glyphs.get(ch) ?? (this.caps ? this.glyphs.get(ch.toUpperCase()) : undefined) ?? this.glyphs.get('?')!;
  }

  width(s: string): number {
    let w = 0;
    for (let i = 0; i < s.length; i++) w += this.get(s[i]).w + 1;
    return Math.max(0, w - 1);
  }

  private atlas(color: string): HTMLCanvasElement {
    if (!this.white) {
      const chars = [...this.glyphs.keys()];
      const c = document.createElement('canvas');
      c.width = ATLAS_COLS * this.cellW;
      c.height = Math.ceil(chars.length / ATLAS_COLS) * this.cellH;
      const ctx = c.getContext('2d')!;
      ctx.fillStyle = '#fff';
      chars.forEach((ch, i) => {
        const g = this.glyphs.get(ch)!;
        g.ax = (i % ATLAS_COLS) * this.cellW;
        g.ay = Math.floor(i / ATLAS_COLS) * this.cellH;
        g.rows.forEach((row, y) => {
          for (let x = 0; x < row.length; x++) if (row[x] === '#') ctx.fillRect(g.ax + x, g.ay + y, 1, 1);
        });
      });
      this.white = c;
    }
    let a = this.tinted.get(color);
    if (!a) {
      a = document.createElement('canvas');
      a.width = this.white.width;
      a.height = this.white.height;
      const ctx = a.getContext('2d')!;
      ctx.drawImage(this.white, 0, 0);
      ctx.globalCompositeOperation = 'source-in';
      ctx.fillStyle = color;
      ctx.fillRect(0, 0, a.width, a.height);
      this.tinted.set(color, a);
    }
    return a;
  }

  /** Draw at an integer scale; returns the advance (the width drawn plus one trailing gap). */
  draw(ctx: CanvasRenderingContext2D, s: string, x: number, y: number, color: string, scale: number): number {
    const atlas = this.atlas(color);
    const h = this.cellH;
    let cx = x;
    for (let i = 0; i < s.length; i++) {
      const g = this.get(s[i]);
      if (s[i] !== ' ') ctx.drawImage(atlas, g.ax, g.ay, g.w, h, cx, y, g.w * scale, h * scale);
      cx += (g.w + 1) * scale;
    }
    return cx - x;
  }
}

const ATLAS_COLS = 16;
const reed = new Face(REED, FONT_H, false);
const frog = new Face(FROG, BIG_H, false);
const pip = new Face(PIP, SMALL_H, true);

// ------------------------------------------------------------------------- Reed, the body face

/** Is there a Reed glyph for this character (anything else draws as '?')? */
export function hasGlyph(ch: string): boolean {
  return reed.has(ch);
}

export function glyphWidth(ch: string): number {
  return reed.get(ch).w;
}

export function textWidth(s: string): number {
  return reed.width(s);
}

/** Cut text to fit a pixel width, ending in '..' when it had to be shortened. */
export function ellipsize(s: string, maxW: number): string {
  if (textWidth(s) <= maxW) return s;
  let t = s;
  while (t.length > 1 && textWidth(t.trimEnd() + '..') > maxW) t = t.slice(0, -1);
  return t.trimEnd() + '..';
}

/** Word-wrap text to a pixel width. Respects explicit '\n'. */
export function wrapText(s: string, maxW: number): string[] {
  const out: string[] = [];
  for (const para of s.split('\n')) {
    const words = para.split(' ');
    let line = '';
    for (const word of words) {
      const test = line ? line + ' ' + word : word;
      if (textWidth(test) > maxW && line) {
        out.push(line);
        line = word;
      } else line = test;
    }
    out.push(line);
  }
  return out;
}

/** Draw Reed text. `scale` is an integer multiplier in current transform units. */
export function drawText(
  ctx: CanvasRenderingContext2D,
  s: string,
  x: number,
  y: number,
  color: string,
  scale = 1,
  shadow: string | null = null,
): number {
  if (shadow) reed.draw(ctx, s, x + scale, y + scale, shadow, scale);
  return reed.draw(ctx, s, x, y, color, scale);
}

